def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open('rb') as f:
        for block in iter(lambda: f.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def main() -> int:
    if not EXE.exists():
        print(f'缺少可执行文件：{EXE}\n请先运行 cargo build --release', file=__import__('sys').stderr)
        return 1
    OUT.mkdir(parents=True, exist_ok=True)

    (OUT / '使用说明.txt').write_text(README, encoding='utf-8', newline='\n')

    zip_path = OUT / '纸间笔记-桌面版.zip'
    with zipfile.ZipFile(zip_path, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        z.write(EXE, '纸间笔记/纸间笔记.exe')
        z.writestr('纸间笔记/使用说明.txt', README)
    print(f'便携版：{zip_path} ({zip_path.stat().st_size:,} 字节)')

    lines = []
    for p in sorted(OUT.iterdir()):
        if p.is_file() and p.name != 'SHA256SUMS.txt':
            lines.append(f'{sha256(p)}  {p.name}')
            print(f'  {p.name}: {p.stat().st_size:,} 字节')
    # 校验和文件必须用 LF：CRLF 会让 sha256sum -c 把回车当成文件名的一部分。
    (OUT / 'SHA256SUMS.txt').write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
